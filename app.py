@app.route("/submit", methods=["POST"])
@limiter.limit("10 per minute;100 per day")
def submit():
    data = request.get_json(silent=True)
    if not data:
        return jsonify({"error": "Request body must be JSON."}), 400

    text = data.get("text", "").strip()
    creator_id = data.get("creator_id", "").strip()

    if not text:
        return jsonify({"error": "The 'text' field is required."}), 400
    if not creator_id:
        return jsonify({"error": "The 'creator_id' field is required."}), 400

    content_id = str(uuid.uuid4())

    # Run both detection signals
    llm_score = llm_signal(text)
    heuristic_score = stylometric_signal(text)

    # Combine into confidence score
    combined_score = compute_confidence(llm_score, heuristic_score)

    # Generate transparency label
    attribution, label_text = generate_label(combined_score)

    # Build audit log entry
    log_entry = {
        "content_id": content_id,
        "creator_id": creator_id,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "attribution": attribution,
        "confidence": combined_score,
        "llm_score": llm_score,
        "heuristic_score": heuristic_score,
        "status": "classified",
        "text_preview": text[:120] + ("..." if len(text) > 120 else ""),
    }
    append_log_entry(log_entry)

    return jsonify({
        "content_id": content_id,
        "attribution": attribution,
        "confidence": combined_score,
        "llm_score": llm_score,
        "heuristic_score": heuristic_score,
        "label": label_text,
        "status": "classified",
    })


@app.route("/appeal", methods=["POST"])
@limiter.limit("5 per minute")
def appeal():
    data = request.get_json(silent=True)
    if not data:
        return jsonify({"error": "Request body must be JSON."}), 400

    content_id = data.get("content_id", "").strip()
    creator_reasoning = data.get("creator_reasoning", "").strip()

    if not content_id:
        return jsonify({"error": "The 'content_id' field is required."}), 400
    if not creator_reasoning:
        return jsonify({"error": "The 'creator_reasoning' field is required."}), 400

    # Find the original classification
    entries = load_audit_log()
    original = None
    for entry in entries:
        if entry.get("content_id") == content_id and entry.get("status") == "classified":
            original = entry
            break

    if not original:
        return jsonify({
            "error": "No classified content found with that content_id. "
                     "It may have already been appealed or does not exist."
        }), 404

    # Update the original entry status
    update_log_entry(content_id, {"status": "under_review"})

    # Append a separate appeal log entry
    appeal_entry = {
        "content_id": content_id,
        "creator_id": original.get("creator_id"),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "type": "appeal",
        "status": "under_review",
        "original_attribution": original.get("attribution"),
        "original_confidence": original.get("confidence"),
        "original_llm_score": original.get("llm_score"),
        "original_heuristic_score": original.get("heuristic_score"),
        "appeal_reasoning": creator_reasoning,
    }
    append_log_entry(appeal_entry)

    return jsonify({
        "message": "Appeal received. Content status updated to under review.",
        "content_id": content_id,
        "status": "under_review",
    })


@app.route("/log", methods=["GET"])
def get_log():
    entries = load_audit_log()
    return jsonify({"entries": entries})


@app.errorhandler(429)
def ratelimit_handler(e):
    return jsonify({
        "error": "Rate limit exceeded. Please wait before submitting again.",
        "retry_after": e.description,
    }), 429


