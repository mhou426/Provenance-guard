groq_client = Groq(api_key=os.getenv("GROQ_API_KEY"))

AUDIT_LOG_FILE = "audit_log.json"


# ---------------------------------------------------------------------------
# Audit log helpers
# ---------------------------------------------------------------------------

def load_audit_log():
    if os.path.exists(AUDIT_LOG_FILE):
        with open(AUDIT_LOG_FILE, "r") as f:
            return json.load(f)
    return []


def save_audit_log(entries):
    with open(AUDIT_LOG_FILE, "w") as f:
        json.dump(entries, f, indent=2)


def append_log_entry(entry):
    entries = load_audit_log()
    entries.append(entry)
    save_audit_log(entries)


def update_log_entry(content_id, updates):
    entries = load_audit_log()
    for entry in entries:
        if entry.get("content_id") == content_id:
            entry.update(updates)
    save_audit_log(entries)


# ---------------------------------------------------------------------------
# Signal 1: LLM-based classification via Groq
# ---------------------------------------------------------------------------

def llm_signal(text):
    """
    Ask the LLM to score how likely the text is AI-generated.
    Returns a float between 0.0 (definitely human) and 1.0 (definitely AI).
    """
    prompt = (
        "You are an AI-content detection expert. Analyze the following text and "
        "estimate the probability that it was generated by an AI language model "
        "rather than written by a human.\n\n"
        "Consider these factors:\n"
        "- Generic or hedging language (e.g. 'it is important to note')\n"
        "- Overly balanced structure with predictable transitions\n"
        "- Lack of personal voice, idiosyncratic word choices, or genuine errors\n"
        "- Uniform sentence rhythm and paragraph length\n\n"
        "Respond with ONLY a JSON object in this exact format, nothing else:\n"
        '{"score": <float between 0.0 and 1.0>, "rationale": "<one sentence>"}\n\n'
        "Text to analyze:\n"
        f'"""\n{text}\n"""'
    )

    try:
        response = groq_client.chat.completions.create(
            model="llama-3.3-70b-versatile",
            messages=[{"role": "user", "content": prompt}],
            temperature=0.1,
            max_tokens=200,
        )
        raw = response.choices[0].message.content.strip()
        # Strip markdown fences if the model wraps its response
        raw = re.sub(r"^```json\s*", "", raw)
        raw = re.sub(r"\s*```$", "", raw)
        parsed = json.loads(raw)
        score = float(parsed.get("score", 0.5))
        return max(0.0, min(1.0, score))
    except Exception as e:
        print(f"LLM signal error: {e}")
        # On failure, return 0.5 (maximally uncertain) so one broken signal
        # does not push the result toward a confident label.
        return 0.5


# ---------------------------------------------------------------------------
# Signal 2: Stylometric heuristics
# ---------------------------------------------------------------------------

def stylometric_signal(text):
    """
    Compute structural statistics that tend to differ between human and AI text.
    Returns a float between 0.0 (human-like) and 1.0 (AI-like).
    """
    sentences = re.split(r'[.!?]+', text)
    sentences = [s.strip() for s in sentences if len(s.strip()) > 0]

    words = re.findall(r"[a-zA-Z']+", text.lower())

    if len(sentences) < 2 or len(words) < 10:
        # Not enough data to be meaningful; return uncertain
        return 0.5

    # --- Metric 1: Sentence length variance ---
    # Human writing has high variance; AI writing clusters around a mean.
    sentence_lengths = [len(re.findall(r"[a-zA-Z']+", s)) for s in sentences]
    if len(sentence_lengths) >= 2:
        stdev = statistics.stdev(sentence_lengths)
        mean_len = statistics.mean(sentence_lengths)
        # Coefficient of variation (normalized variance)
        cv = stdev / mean_len if mean_len > 0 else 0
        # Human writing typically has CV > 0.5; AI text is often < 0.3
        # Map: CV >= 0.6 -> 0.0 (very human), CV <= 0.15 -> 1.0 (very AI)
        variance_score = max(0.0, min(1.0, 1.0 - ((cv - 0.15) / 0.45)))
    else:
        variance_score = 0.5

    # --- Metric 2: Type-token ratio (vocabulary diversity) ---
    # Higher TTR = more diverse vocab = more human-like
    unique_words = set(words)
    ttr = len(unique_words) / len(words) if len(words) > 0 else 0
    # For passages of typical length (50-500 words), human TTR is often > 0.65
    # AI text tends toward 0.45-0.60
    # Map: TTR >= 0.75 -> 0.0 (human), TTR <= 0.45 -> 1.0 (AI)
    ttr_score = max(0.0, min(1.0, 1.0 - ((ttr - 0.45) / 0.30)))

    # --- Metric 3: Punctuation density ---
    # Human writing uses more varied and frequent punctuation
    punct_chars = sum(1 for c in text if c in ".,!?;:—-–()\"'…")
    total_chars = len(text)
    punct_density = punct_chars / total_chars if total_chars > 0 else 0
    # Human text: ~0.06-0.10 density; AI text: ~0.03-0.05
    # Map: density >= 0.08 -> 0.0 (human), density <= 0.03 -> 1.0 (AI)
    punct_score = max(0.0, min(1.0, 1.0 - ((punct_density - 0.03) / 0.05)))

    # Average the three sub-metrics
    combined = (variance_score + ttr_score + punct_score) / 3.0
    return round(combined, 4)


# ---------------------------------------------------------------------------
# Confidence scoring
# ---------------------------------------------------------------------------

def compute_confidence(llm_score, heuristic_score):
    """
    Weighted average of the two signals.
    Returns combined score between 0.0 and 1.0.
    """
    combined = (0.6 * llm_score) + (0.4 * heuristic_score)
    return round(combined, 4)


# ---------------------------------------------------------------------------
# Transparency label
# ---------------------------------------------------------------------------

def generate_label(combined_score):
    """
    Map combined confidence score to a human-readable transparency label.
    Returns (attribution, label_text).
    """
    if combined_score >= 0.75:
        pct = round(combined_score * 100)
        return (
            "likely_ai",
            f"Our analysis indicates this content is likely AI-generated "
            f"(confidence: {pct}%). If you believe this is incorrect, you "
            f"can submit an appeal."
        )
    elif combined_score >= 0.40:
        pct = round(combined_score * 100)
        return (
            "uncertain",
            f"Our analysis was inconclusive for this content "
            f"(confidence: {pct}%). The result may reflect either "
            f"AI-assisted or human-written text. If you believe this "
            f"result is wrong, you can submit an appeal."
        )
    else:
        pct = round((1 - combined_score) * 100)
        return (
            "likely_human",
            f"Our analysis indicates this content is likely human-written "
            f"(confidence: {pct}%). No action is needed."
        )


